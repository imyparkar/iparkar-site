/* iParkar Learning — top navigation
   ---------------------------------------------------------------------------
   The header markup is generated by build.mjs from `nav` in site-config.js,
   so desktop and mobile share one list. This script only adds behaviour:

   • Resources and Practice Exam: the label is a link to the overview page; the
     chevron button beside it opens the menu (aria-expanded). Click, tap, Enter,
     Space and Escape all work; Escape closes the open menu and returns focus to
     its toggle. ArrowDown on an open toggle moves into the menu.
   • Phones and tablets (≤1150px): a Menu button opens the same list as a panel,
     with the two menus as expandable groups.
   • Sign in / Dashboard: asks app.iparkar.com whether this browser has a valid
     learner session. The answer is only a yes/no; no token is read or stored
     here, and the session cookie never leaves app.iparkar.com. If the check
     fails or the session has expired, visitors see Sign in.
   --------------------------------------------------------------------------- */
(function () {
  "use strict";
  var doc = document.documentElement;
  doc.classList.add("js");
  var header = document.querySelector("[data-site-nav]");
  if (!header) return;

  var APP = "https://app.iparkar.com";
  var mobileQuery = window.matchMedia ? window.matchMedia("(max-width: 1150px)") : { matches: false };
  var burger = header.querySelector("[data-nav-burger]");
  var groups = Array.prototype.slice.call(header.querySelectorAll("[data-nav-group]"));

  function toggleOf(group) { return group.querySelector("[data-nav-toggle]"); }
  function isOpen(group) { return group.classList.contains("is-open"); }
  function setGroup(group, open) {
    group.classList.toggle("is-open", open);
    var t = toggleOf(group);
    if (t) t.setAttribute("aria-expanded", open ? "true" : "false");
  }
  function closeGroups(except) { groups.forEach(function (g) { if (g !== except) setGroup(g, false); }); }
  function openGroup() { for (var i = 0; i < groups.length; i++) if (isOpen(groups[i])) return groups[i]; return null; }

  function menuOpen() { return doc.classList.contains("nav-open"); }
  function setMenu(open) {
    if (!burger) return;
    doc.classList.toggle("nav-open", open);
    burger.setAttribute("aria-expanded", open ? "true" : "false");
    var text = burger.querySelector(".nav-burger__text");
    if (text) text.textContent = open ? "Close" : "Menu";
    if (open) {
      // Expand the group for the page you are on, so its sub-pages are one tap away.
      groups.forEach(function (g) { if (g.querySelector('[aria-current]')) setGroup(g, true); });
    } else {
      closeGroups();
    }
  }

  groups.forEach(function (group) {
    var toggle = toggleOf(group);
    if (!toggle) return;
    toggle.addEventListener("click", function () {
      var open = !isOpen(group);
      if (!mobileQuery.matches) closeGroups(group);
      setGroup(group, open);
    });
    toggle.addEventListener("keydown", function (e) {
      if (e.key === "ArrowDown") {
        e.preventDefault();
        if (!mobileQuery.matches) closeGroups(group);
        setGroup(group, true);
        var first = group.querySelector(".nav-menu a");
        if (first) first.focus();
      }
    });
    // Desktop: a dropdown closes when keyboard focus leaves it.
    group.addEventListener("focusout", function (e) {
      if (mobileQuery.matches) return;
      if (e.relatedTarget && group.contains(e.relatedTarget)) return;
      if (e.relatedTarget) setGroup(group, false);
    });
  });

  if (burger) burger.addEventListener("click", function () { setMenu(!menuOpen()); });

  document.addEventListener("keydown", function (e) {
    if (e.key !== "Escape" && e.key !== "Esc") return;
    var g = openGroup();
    if (g) {
      setGroup(g, false);
      var t = toggleOf(g);
      if (t) t.focus();
      e.preventDefault();
      return;
    }
    if (menuOpen()) { setMenu(false); burger.focus(); e.preventDefault(); }
  });

  // Click or tap outside the header closes whatever is open.
  document.addEventListener("click", function (e) {
    if (header.contains(e.target)) return;
    if (!mobileQuery.matches) closeGroups();
    if (menuOpen()) setMenu(false);
  });

  // Moving between phone and desktop layouts resets the menus.
  function reset() { closeGroups(); if (menuOpen()) setMenu(false); }
  if (mobileQuery.addEventListener) mobileQuery.addEventListener("change", reset);
  else if (mobileQuery.addListener) mobileQuery.addListener(reset);

  /* ---------- Sign in / Dashboard ---------- */
  var auth = header.querySelector("[data-auth-link]");
  if (!auth || typeof fetch !== "function") return;
  var KEY = "ip-session";
  function show(signedIn) {
    auth.textContent = signedIn ? "Dashboard" : "Sign in";
    auth.href = APP + (signedIn ? "/dashboard" : "/login");
    auth.classList.toggle("is-dashboard", !!signedIn);
  }
  // A recent answer avoids a flash on every page; it is re-checked in the background.
  try {
    var cached = JSON.parse(sessionStorage.getItem(KEY) || "null");
    if (cached && Date.now() - cached.t < 120000) show(cached.signedIn === true);
  } catch (e) {}
  fetch(APP + "/api/session", { credentials: "include", cache: "no-store", mode: "cors" })
    .then(function (r) { return r.ok ? r.json() : { signedIn: false }; })
    .catch(function () { return { signedIn: false }; })
    .then(function (d) {
      var signedIn = !!(d && d.signedIn === true);
      show(signedIn);
      try { sessionStorage.setItem(KEY, JSON.stringify({ signedIn: signedIn, t: Date.now() })); } catch (e) {}
    });
})();
